#!/usr/bin/env bash
# ============================================================================
# update-deps.sh — 生成 internal/deps/versions.go（固定 mise / chezmoi 版本与 sha256）
# 校验值取自上游 Release 的官方 checksum 文件，写进源码后由 dsync 下载时逐字节校验。
# 用法（cli/ 目录）：bash scripts/update-deps.sh <mise 版本> <chezmoi 版本>
#   例：bash scripts/update-deps.sh 2026.9.0 2.72.1
# ============================================================================
set -euo pipefail

MISE="${1:?用法: update-deps.sh <mise 版本> <chezmoi 版本>}"
CHEZMOI="${2:?用法: update-deps.sh <mise 版本> <chezmoi 版本>}"
CLI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$CLI_DIR/internal/deps/versions.go"

mise_sums="$(curl -fsSL "https://github.com/jdx/mise/releases/download/v$MISE/SHASUMS256.txt")"
chezmoi_sums="$(curl -fsSL "https://github.com/twpayne/chezmoi/releases/download/v$CHEZMOI/chezmoi_${CHEZMOI}_checksums.txt")"

sum() { # $1=checksum 文件内容 $2=资产名；找不到即失败
  local s
  s="$(printf '%s\n' "$1" | awk -v n="$2" '{f=$2; sub(/^\.\//, "", f)} f==n {print $1}')"
  [ -n "$s" ] || { echo "找不到资产 $2 的校验值" >&2; exit 1; }
  printf '%s' "$s"
}

{
  echo "// Code generated by scripts/update-deps.sh; DO NOT EDIT."
  echo
  echo "package deps"
  echo
  echo "// Mise 是 dsync 安装的 mise 版本（裸二进制）。"
  echo "var Mise = Tool{"
  echo "	Name:    \"mise\","
  echo "	Version: \"$MISE\","
  echo "	Assets: map[string]Asset{"
  for p in linux/amd64:linux-x64 linux/arm64:linux-arm64 darwin/amd64:macos-x64 darwin/arm64:macos-arm64; do
    key="${p%%:*}"; name="mise-v$MISE-${p#*:}"
    echo "		\"$key\": {URL: \"https://github.com/jdx/mise/releases/download/v$MISE/$name\", SHA256: \"$(sum "$mise_sums" "$name")\"},"
  done
  echo "	},"
  echo "}"
  echo
  echo "// Chezmoi 是 dsync 安装的 chezmoi 版本（tar.gz 中的 chezmoi 文件）。"
  echo "var Chezmoi = Tool{"
  echo "	Name:    \"chezmoi\","
  echo "	Version: \"$CHEZMOI\","
  echo "	Assets: map[string]Asset{"
  for p in linux/amd64:linux_amd64 linux/arm64:linux_arm64 darwin/amd64:darwin_amd64 darwin/arm64:darwin_arm64; do
    key="${p%%:*}"; name="chezmoi_${CHEZMOI}_${p#*:}.tar.gz"
    echo "		\"$key\": {URL: \"https://github.com/twpayne/chezmoi/releases/download/v$CHEZMOI/$name\", SHA256: \"$(sum "$chezmoi_sums" "$name")\", Member: \"chezmoi\"},"
  done
  echo "	},"
  echo "}"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
gofmt -w "$OUT" 2>/dev/null || true
echo "已生成 $OUT（mise $MISE / chezmoi $CHEZMOI）"
